// Formatting helpers available in every view as `h`.
const config = require('../config');

const dateFmt = new Intl.DateTimeFormat('en-PH', {
  month: 'short', day: 'numeric', year: 'numeric', timeZone: config.timezone,
});
const dateTimeFmt = new Intl.DateTimeFormat('en-PH', {
  month: 'short', day: 'numeric', year: 'numeric', hour: 'numeric', minute: '2-digit', timeZone: config.timezone,
});
const monthFmt = new Intl.DateTimeFormat('en-PH', { month: 'short', year: '2-digit', timeZone: 'UTC' });

const formatDate = (d) => (d ? dateFmt.format(new Date(d)) : '');
const formatDateTime = (d) => (d ? dateTimeFmt.format(new Date(d)) : '');

function timeAgo(d) {
  if (!d) return '';
  const minutes = Math.round((Date.now() - new Date(d).getTime()) / 60000);
  if (minutes < 1) return 'just now';
  if (minutes < 60) return `${minutes} min ago`;
  const hours = Math.round(minutes / 60);
  if (hours < 24) return `${hours} hr ago`;
  const days = Math.round(hours / 24);
  if (days < 30) return `${days} day${days === 1 ? '' : 's'} ago`;
  return formatDate(d);
}

// '2026-11' -> 'Nov 26'
const formatMonth = (yyyyMm) => monthFmt.format(new Date(`${yyyyMm}-01T00:00:00Z`));

function duration(hours) {
  if (hours === null || hours === undefined) return '—';
  if (hours < 1) return 'under 1 hr';
  if (hours < 48) return `${Math.round(hours)} hr`;
  return `${(hours / 24).toFixed(1)} days`;
}

function hoursBetween(start, end) {
  return (new Date(end).getTime() - new Date(start).getTime()) / 3600000;
}

const STATUS_CLASS = { Pending: 'pending', 'In Progress': 'progress', Resolved: 'resolved' };
const statusClass = (status) => STATUS_CLASS[status] || 'pending';

function address(row) {
  const parts = [`${row.house_number} ${row.street}`, `Brgy. ${row.barangay}`, row.city];
  return parts.join(', ') + (row.postal_code ? ` ${row.postal_code}` : '');
}

function fileSize(bytes) {
  if (bytes < 1024) return `${bytes} B`;
  if (bytes < 1024 * 1024) return `${Math.round(bytes / 1024)} KB`;
  return `${(bytes / (1024 * 1024)).toFixed(1)} MB`;
}

const plural = (n, word, pluralWord = `${word}s`) => `${n.toLocaleString('en-PH')} ${n === 1 ? word : pluralWord}`;

const number = (n) => Number(n || 0).toLocaleString('en-PH');

const percent = (part, whole) => (whole ? Math.round((part / whole) * 100) : 0);

// Axis for count charts: a round top value and evenly spaced integer ticks.
function niceScale(max, count = 4) {
  const rough = Math.max(1, max) / count;
  const pow = 10 ** Math.floor(Math.log10(rough));
  const step = Math.max(1, Math.ceil([1, 2, 2.5, 5, 10].map((m) => m * pow).find((s) => s >= rough)));
  const top = step * count;
  return { top, ticks: Array.from({ length: count + 1 }, (_, i) => top - i * step) };
}

// Builds a query string from the current filters with some values replaced.
function query(base, overrides = {}) {
  const params = new URLSearchParams();
  for (const [key, value] of Object.entries({ ...base, ...overrides })) {
    if (value !== undefined && value !== null && value !== '') params.set(key, value);
  }
  const s = params.toString();
  return s ? `?${s}` : '';
}

