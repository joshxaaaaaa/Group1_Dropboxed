function icon(name, className = 'icon') {
  return `<svg class="${className}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${ICONS[name] || ICONS.tag}</svg>`;
}

function categoryIcon(categoryName = '') {
  const name = categoryName.toLowerCase();
  if (name.includes('rust') || name.includes('contamin')) return 'droplet';
  if (name.includes('pressure')) return 'gauge';
  if (name.includes('odor') || name.includes('smell')) return 'wind';
  if (name.includes('leak')) return 'wrench';
  return 'tag';
}

